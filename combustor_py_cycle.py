"""
combustor_pycycle_integration.py
---------------------------------
Self-contained A4 variation study with physics-based combustor pressure drop.

Edit the CYCLE CONFIG block in __main__ to change:
  - Maps (comp_map, turb_map)
  - Design targets (Fn, T4, OPR, Nmech, ...)
  - A4 sweep range and resolution
  - Thrust levels for Study 2
  - Turbine area mode ('sWp' or 'alpha')

Turbine area variation modes
-----------------------------
  'sWp'   : s_Wp *= a4_scalar  — works with any map
  'alpha' : turb.map.alphaMap = a4_scalar  — requires variable-area alphaMap
            (generated by generate_turbine_map.py with area_fracs as alphaMap)

Combustor pressure drop model
------------------------------
  Total-to-total orifice:
    mdot = CdA * sqrt(2 * rho_t3 * (Pt3 - Pt4))
    pi_b = 1 - (mdot/CdA)^2 / (2 * rho_t3 * Pt3)
  CdA back-calculated from design point at fixed reference dPqP.
"""
