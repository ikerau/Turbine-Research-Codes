def rho_total(Tt_K, Pt_Pa):
    g = ct.Solution("gri30.yaml")
    g.TPX = Tt_K, Pt_Pa, "O2:0.21, N2:0.79"
    return float(g.density)


# ══════════════════════════════════════════════════════════════════════════════
#  COMBUSTOR PRESSURE DROP MODEL
# ══════════════════════════════════════════════════════════════════════════════

def physics_pib(Pt3_Pa, Tt3_K, mdot_si, CdA):
    rho_t3 = rho_total(Tt3_K, Pt3_Pa)
    dPt    = (mdot_si / CdA) ** 2 / (2.0 * rho_t3)
    dPqP   = dPt / Pt3_Pa
    return float(1.0 - dPqP), float(dPqP)


def calc_CdA_liner(Tt3_K, Pt3_Pa, mdot_si, dPqP_ref=None):
    if dPqP_ref is None:
        dPqP_ref = DPQP_FIXED
    rho_t3 = rho_total(Tt3_K, Pt3_Pa)
    dPt    = dPqP_ref * Pt3_Pa
    return float(mdot_si / np.sqrt(2.0 * rho_t3 * dPt))


