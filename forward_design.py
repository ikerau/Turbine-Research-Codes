# ═══════════════════════════════════════════════════════════════════════════════
#  forward_design_impulse  —  SUPERSONIC IMPULSE PARTIAL-ADMISSION TURBINE
#
#  Drop into forward_design.py.  Requirements:
#    1. design_point_kinematics accepts impulse=True (exit triangle with swirl)
#    2. _walk_thermo uses kin['C3'] instead of Cm at the absolute exit
#    3. _compute_eta / _build_state_dicts use kin['C3']
#    4. compute_blade_losses_impulse exists in off_design.py
#
#  Geometry model — no Pritchard anywhere:
#    - Nozzle  : N_nozzles rectangular CD passages
#                throat/exit widths from mdot + isentropic A/A*(M2)
#    - Rotor   : symmetric impulse, β1_metal = β2_metal = β1_flow
#                throat from continuity at choke:
#                    o/t = cos(β2) · q_n(λW, n, γ) / q_n(λcrit, n, γ)
#    - Stagger : nozzle = α2;  rotor = metal angle (symmetric blade)
#
# ═══════════════════════════════════════════════════════════════════════════════

def design_point_kinematics_impulse(
    *, Tt0, Pt0, gas, mdot, RPM, Rm, alpha2_deg, W_t,
):

    # Fixed quantities
    omega_si = float(RPM.to('rad/s').magnitude)
    Rm_m     = float(Rm.to('m').magnitude)
    U_val    = omega_si * Rm_m
    dH       = float(W_t.to('W').magnitude) / float(mdot.to('kg/s').magnitude)

    # Derive phi and psi from alpha2
    psi_val    = dH / U_val**2
    alpha2_rad = np.radians(alpha2_deg)

    # C_theta2 = psi * U (original function convention)
    # C2 * sin(alpha2) = C_theta2  →  C2 = C_theta2 / sin(alpha2)
    # Cm = C2 * cos(alpha2) = C_theta2 * cos(alpha2)/sin(alpha2) = C_theta2/tan(alpha2)
    C_theta2 = psi_val * U_val
    phi_val  = C_theta2 / (U_val * np.tan(alpha2_rad))

    return design_point_kinematics(
        Tt0     = Tt0,
        Pt0     = Pt0,
        gas     = gas,
        mdot    = mdot,
        RPM     = RPM,
        psi     = psi_val,
        phi     = phi_val,
        W_t     = W_t,
        impulse = True,
    )
# ═══════════════════════════════════════════════════════════════════════════════
#  PARTIAL-ADMISSION CORRECTION  (NASA SP-8110 / MATLAB form, imperial)
# ═══════════════════════════════════════════════════════════════════════════════
def partial_admission_correction(*, eta_ts, U, C2, C3,
                                  Ps_rotor_in, Ts_rotor_in, R_rotor_in,
                                  rotor_pitch, f_arc, D_turb, RPM):
    """
    SP-8110 Eq. 12 + 14 partial-admission efficiency.

    eta_ts      : thermodynamic T-S efficiency at design (used as η_FA baseline)
    U           : blade speed [m/s]
    C2          : absolute nozzle exit velocity [m/s]  (= C_o in SP-8110)
    C3          : absolute rotor exit velocity [m/s]
    f_arc       : active nozzle arc length at mean radius [m]
    D_turb      : mean rotor diameter [m]
    RPM         : shaft speed [rev/min]

    SP-8110 Eq. 12 uses N in rev/sec and rho in lbm/ft³.
    The 5.6e-5 coefficient carries implicit units ft³·sec/lbm to make
    the windage term dimensionless.
    """
    # Admission fraction ε = F in SP-8110 notation
    eps = f_arc / (np.pi * D_turb)
    eps = float(np.clip(eps, 0.01, 1.0))

    # K = exit/inlet velocity ratio (rotor)
    K = C3 / C2

    # Sector (scavenging + momentum) factor — SP-8110 Eq. 13
    # Valid when f_arc > p/3, i.e. arc covers at least one blade pitch
    sector_factor = (1.0 + K * (1.0 - rotor_pitch / (3.0 * f_arc))) / (1.0 + K)
    sector_factor = float(np.clip(sector_factor, 0.0, 1.0))

    # Windage — SP-8110 Eq. 12
    # N must be in rev/sec, rho in lbm/ft³
    N_rps    = RPM / 60.0                               # rev/min → rev/sec
    rho_si   = Ps_rotor_in / (R_rotor_in * Ts_rotor_in)
    rho_imp  = rho_si * 0.062428                        # kg/m³ → lbm/ft³
    VR       = U / C2                                   # = U/C_o
    windage  = 5.6e-5 * VR**2 * rho_imp * N_rps * (1.0 - eps) / eps

    eta_partial = sector_factor * eta_ts - windage

    return dict(
        eta_partial   = float(eta_partial),
        eta_full      = float(eta_ts),
        admission_eps = float(eps),
        K             = float(K),
        VR            = float(VR),
        sector_factor = float(sector_factor),
        windage       = float(windage),
        f_arc_m       = float(f_arc),
        rho_si_kgm3   = float(rho_si),
    )


# ═══════════════════════════════════════════════════════════════════════════════
#  NOZZLE GEOMETRY  —  rectangular CD passage
# ═══════════════════════════════════════════════════════════════════════════════
def _isentropic_area_ratio(M, gamma):
    """A/A* for isentropic quasi-1D flow."""
    gm1 = gamma - 1.0
    gp1 = gamma + 1.0
    return (1.0 / M) * ((2.0 / gp1) * (1.0 + 0.5 * gm1 * M**2)) ** (gp1 / (2.0 * gm1))


def _build_nozzle_geometry(kin, states, annulus, mdot_kg,
                            LE_radius, TE_radius, AR_nozzle=2.0):
    
    Pt_mag  = float(kin['Pt0'].to('Pa').magnitude)
    Tt_mag  = float(kin['Tt0'].to('K').magnitude)
    gamma_2 = states['gamma2']
    R_2     = states['R2']
    M_C2    = states['M_C2']
    alpha_2 = kin['alpha2']

    # Known from annulus (set by epsilon)
    f_arc        = annulus['f_arc']
    blade_height = annulus['stator_exit']['span']
    Rm           = kin['Rm']

    # Total throat area from choked mass flow
    gp1 = gamma_2 + 1.0
    gm1 = gamma_2 - 1.0
    mf_term      = np.sqrt((gamma_2 / R_2) * (2.0 / gp1) ** (gp1 / gm1))
    A_star_total = (mdot_kg * np.sqrt(Tt_mag) / Pt_mag) / mf_term
    A_exit_total = A_star_total * _isentropic_area_ratio(M_C2, gamma_2)

    N_nozzles_AR = A_star_total / (blade_height**2 * AR_nozzle)

    # Also constrain by how many passages fit in the active arc
    o_ex_single   = A_exit_total / blade_height          # if N=1
    f_arc_circ    = f_arc * np.cos(np.radians(alpha_2))  # circumferential projection
    N_nozzles_arc = f_arc_circ / o_ex_single             # how many fit in arc

    # Take the binding constraint — whichever requires more passages
    N_nozzles = max(1, round(max(N_nozzles_AR, N_nozzles_arc)))

    # Per-passage areas and widths
    A_star_per = A_star_total / N_nozzles
    A_exit_per = A_exit_total / N_nozzles
    o_th       = A_star_per / blade_height
    o_ex       = A_exit_per / blade_height

    # Pitch and epsilon (diagnostic — should match input epsilon)
    t_pitch = 2.0 * np.pi * Rm / N_nozzles
    epsilon = f_arc / (np.pi * 2.0 * Rm)

    # Nozzle radii centered on Rm
    Ro = Rm + 0.5 * blade_height
    Ri = Rm - 0.5 * blade_height

    return {
        "Beta_1":     Q_(0.0,      'deg'),
        "Beta_2":     Q_(alpha_2,  'deg'),
        "throat":     Q_(o_th,     'm'),
        "Chord_ax":   Q_(blade_height / AR_nozzle, 'm'),
        "Blade_N":    int(N_nozzles),
        "Tip_Gap":    Q_(0.0,      'm'),
        "LE_radius":  LE_radius,
        "TE_radius":  TE_radius,
        "R_o_outlet": Q_(Ro,       'm'),
        "R_i_outlet": Q_(Ri,       'm'),
        "R_o_inlet":  Q_(Ro,       'm'),
        "R_i_inlet":  Q_(Ri,       'm'),
        "stagger":    Q_(alpha_2,  'deg'),
        "exit_wedge": Q_(0.0,      'deg'),
        "zeta_ung":   Q_(0.0,      'deg'),
        "rotating":   False,

        # Diagnostics
        "_N":                int(N_nozzles),
        "_throat_mm":        o_th * 1000,
        "_exit_mm":          o_ex * 1000,
        "_pitch_mm":         t_pitch * 1000,
        "_span_mm":          blade_height * 1000,
        "_A_star_total_mm2": A_star_total * 1e6,
        "_A_exit_per_mm2":   A_exit_per * 1e6,
        "_A_A_star":         A_exit_per / A_star_per,
        "_alpha_2_deg":      alpha_2,
        "_M_C2":             M_C2,
        "_f_arc_m":          f_arc,
        "_admission_eps":    epsilon,
    }

# ═══════════════════════════════════════════════════════════════════════════════
#  ROTOR GEOMETRY  —  minimal symmetric impulse (no MoC)
# ═══════════════════════════════════════════════════════════════════════════════
def _build_rotor_geometry_impulse(kin, states, annulus,
                                    AR_rotor, Z_rotor, tip_gap,
                                    LE_radius, TE_radius,
                                    r_loss_r=1.0, tip_percent = None):
    """
    Symmetric impulse: β1_metal = β2_metal = |β1_flow| (zero incidence).

    PITCH is set by Zweifel's optimum loading coefficient:
        Z = 2·(s/c)·cos²(β2)·(tan β1 + tan β2)

    For a symmetric impulse rotor (β1 = β2 = β_flow, opposite signs across
    the row but same magnitude), the loading sum (tan β1 + tan β2) = 2·tan β_flow,
    so the closed-form pitch falls out as:
        s/c = Z / (4·tan β_flow · cos² β_flow)
        s   = (s/c) · Cax

    Throat follows continuity at choke (unchanged from the MoC variant):
        o/t = cos(β2) · q_n(λW, n, γ) / q_n(λcrit, n, γ)

    LE_radius / TE_radius used by _size_annulus for blockage.

    The MoC-derived blade profile and surface Mach distributions are NOT
    computed here — call moc_blade() separately on the converged design if
    a manufacturable profile is required.
    """
    Rm         = kin['Rm']
    beta_flow  = abs(kin['beta2'])                  # axial, positive (deg)
    lam_exit   = states['lam_W3']                   # = λW2 by symmetry
    lam_W2     = states['lam_W2']                   # rotor-inlet rel. lambda
    gamma_in   = states['gamma2']                   # γ at rotor inlet
    gamma_exit = states['gamma3']
    Ps_exit    = states['Ps3']
    
    # Rotor inlet relative Mach — kept as a diagnostic
    M_w1 = lambda_to_mach(lam_W2, gamma_in)

    ann      = annulus['rotor_exit']
    if tip_percent is not None:
        tip_gap = Q_(ann['span']*tip_percent,'m')
    
    span_out = ann['span'] - float(tip_gap.to('m').magnitude)

    # Chord from aspect ratio
    Cax = span_out / AR_rotor

    tb = np.tan(np.radians(beta_flow))
    cb = np.cos(np.radians(beta_flow))
    
    
    # ── Zweifel-driven pitch ─────────────────────────────────────────────
    # Symmetric impulse: tan β1 + tan β2 = 2·tan β_flow
    # Solve Z = 2·(s/c)·cos²β·(2·tan β)  →  s/c = Z / (4·tan β · cos² β)
    s_over_c = Z_rotor / (4.0 * tb * cb**2)
    pitch_zwf = s_over_c * Cax

    N_float = 2.0 * np.pi * Rm / pitch_zwf
    N       = max(int(round(N_float)), 3)
    t_pitch = 2.0 * np.pi * Rm / N

    # Recompute the actual Zweifel that the integer-rounded N gives
    Z_actual = 2.0 * (t_pitch / Cax) * (2.0 * tb) * cb**2

    # Polytropic exponent from r_loss (same logic as main builder)
    Pt_mag = float(states['Pt2_rel'])
    Pt_out = Pt_mag * r_loss_r
    if Pt_mag / Ps_exit > 1.0 and Pt_out / Ps_exit > 1.0 and r_loss_r < 1.0:
        gm1        = gamma_exit - 1.0
        n_over_nm1 = ((gamma_exit / gm1)
                      * np.log(Pt_mag  / Ps_exit)
                      / np.log(Pt_out / Ps_exit))
        n_poly = float(np.clip(n_over_nm1 / (n_over_nm1 - 1.0), 1.01, gamma_exit))
    else:
        n_poly = gamma_exit
    lam_crit_val = lam_crit_polytropic(n_poly, gamma_exit)

    # Throat from continuity at choke: o/t = cos(β)·q(λ)/q(λcrit)
    q_lam  = _q_func(lam_exit,     gamma_exit)
    q_crit = _q_func(lam_crit_val, gamma_exit)
    o_over_t = cb * q_lam / q_crit
    o_over_t = float(np.clip(o_over_t, 0.05, cb))
    o        = o_over_t * t_pitch

    beta_metal  = beta_flow
    stagger_deg = beta_metal

    ann_in = annulus['rotor_inlet']

    return {
        "Beta_1":     Q_(beta_metal,  'deg'),
        "Beta_2":     Q_(beta_metal,  'deg'),
        "throat":     Q_(o,           'm'),
        "Chord_ax":   Q_(Cax,         'm'),
        "Blade_N":    int(N),
        "Tip_Gap":    tip_gap,
        "LE_radius":  LE_radius,
        "TE_radius":  TE_radius,
        "R_o_outlet": Q_(ann['Ro'],    'm'),
        "R_i_outlet": Q_(ann['Ri'],    'm'),
        "R_o_inlet":  Q_(ann_in['Ro'], 'm'),
        "R_i_inlet":  Q_(ann_in['Ri'], 'm'),
        "stagger":    Q_(stagger_deg, 'deg'),
        "exit_wedge": Q_(0.0,         'deg'),
        "zeta_ung":   Q_(0.0,         'deg'),
        "rotating":   True,

        # MoC fields kept for return-shape compatibility, set to None.
        # Call moc_blade() separately on the converged design if needed.
        "moc":             None,
        "moc_x":           None,
        "moc_y":           None,
        "moc_x_segments":  None,
        "moc_y_segments":  None,

        # Diagnostics
        "_N":                int(N),
        "_Cax_mm":           Cax * 1000,
        "_throat_mm":        o * 1000,
        "_pitch_mm":         t_pitch * 1000,
        "_pitch_moc_mm":     None,                 # MoC not run
        "_pitch_zweifel_mm": pitch_zwf * 1000,
        "_span_mm":          span_out * 1000,
        "_o_over_t":         o_over_t,
        "_o_over_t_gauge":   float(cb),
        "_n_poly":           n_poly,
        "_lam_crit":         lam_crit_val,
        "_lam_exit":         float(lam_exit),
        "_lam_W2":           float(lam_W2),
        "_M_w1":             float(M_w1),
        "_Zweifel_target":   float(Z_rotor),
        "_Zweifel":          float(Z_actual),

        # MoC-derived diagnostics — set to None
        "_moc_M_l":          None,
        "_moc_M_u":          None,
        "_moc_passage_mm":   None,
        "_moc_thickness_mm": None,
        "_moc_Rstar_l_mm":   None,
        "_moc_Rstar_u_mm":   None,
    }

def _size_annulus_impulse(kin, states, mdot_kg, epsilon,
                           stator_blade=None, rotor_blade=None):
    """
    Partial admission annulus sizing.
    Equivalent to sizing for full admission with mdot scaled by 1/epsilon,
    since the flow is concentrated in fraction epsilon of the circumference.
    """
    mdot_eff = mdot_kg / epsilon
    annulus  = _size_annulus(kin, states, mdot_eff,
                              stator_blade=stator_blade,
                              rotor_blade=rotor_blade)
    # Tag epsilon and f_arc onto the result for downstream use
    f_arc = epsilon * np.pi * 2.0 * kin['Rm']
    annulus['epsilon'] = epsilon
    annulus['f_arc']   = f_arc
    return annulus

def eta_volumetric_ovsyannikov(blade, kin, states, phi_nozzle=0.975,
                                lambda_seal=1.00, tau_y=1.0):
    """
    Ovsyannikov-Borovskiy (1986) volumetric efficiency correction
    for radial tip clearance leakage in unshrouded supersonic impulse turbines.
    Hahn et al. (ISTS 2019) Eqs. 1-4.

    Models leakage as a fraction of turbine mass flow that bypasses
    the rotor entirely — appropriate for impulse blades where there is
    negligible blade-to-blade pressure difference driving leakage.

    Parameters
    ----------
    blade       : rotor blade dict
    kin         : kinematics dict (needs alpha2, Rm)
    states      : thermodynamic states dict (needs rho2, gamma2)
    phi_nozzle  : nozzle velocity coefficient φ_c (default 0.975)
    lambda_seal : sealing design factor λ (default 0.75, typical for
                  open radial gap without labyrinth)
    tau_y       : sealing pitch ratio τ_y (default 1.0)

    Returns
    -------
    eta_vol : float
        Volumetric efficiency [0, 1].
        Apply as: eta_ts_corrected = eta_ts * eta_vol
    mdot_leak_fraction : float
        Leakage mass flow / total mass flow (diagnostic)
    """
    # ── Geometry ─────────────────────────────────────────────────────────
    Delta   = float(blade['Tip_Gap'].to('m').magnitude)          # radial clearance Δ
    h1      = float((blade['R_o_outlet'] - blade['R_i_outlet']
                     - blade['Tip_Gap']).to('m').magnitude)       # blade height h₁ᵢ
    D_cp    = 2.0 * float(kin['Rm'])                              # meridional diameter

    if h1 <= 0 or Delta <= 0:
        return 1.0, 0.0

    # ── Stator exit angle (from axial convention → convert to α_1T) ──────
    # α_1T in Ovsyannikov is measured from tangential, same as β_tang
    # α_1T = 90° - alpha2 (where alpha2 is from axial in our convention)
    alpha_1T_rad = np.radians(90.0 - kin['alpha2'])

    # ── Eq. 4: flow coefficient μ_заз ────────────────────────────────────
    # μ_заз = sqrt(4·Δ / λ·τ_y)
    mu_zaz = np.sqrt(4.0 * Delta / (lambda_seal * tau_y))

    # ── Eq. 3: geometric factor r_g ───────────────────────────────────────
    # r_g = [1 + h₁ᵢ/D_cp] · [2·Δ/h₁ᵢ]
    r_g = (1.0 + h1 / D_cp) * (2.0 * Delta / h1)

    # ── Eq. 2: leakage flow factor f_y ───────────────────────────────────
    # f_y = sqrt(1 + [ρ_T · {(1/φ_c²)·sin²(α_1T) − 1}]) · r_g
    # ρ_T here is the total-to-static pressure ratio (= 1/isentropic p-ratio
    # at nozzle exit) — i.e. the stage expansion ratio seen by the stator
    # In our notation: rho_T = Pt0 / Ps2 (stage total-to-static PR)
    rho_T   = float(states['Pt0']) / float(states['Ps2']) \
              if 'Pt0' in states else 1.0 / isentropic_p_P0(
                  mach_to_lambda(states['M_C2'], states['gamma2']),
                  states['gamma2']
              )

    sin2_a  = np.sin(alpha_1T_rad)**2
    bracket = rho_T * ((1.0 / phi_nozzle**2) * sin2_a - 1.0)
    bracket = max(bracket, 0.0)    # guard: can go slightly negative at low PR

    f_y = np.sqrt(1.0 + bracket) * r_g

    # ── Eq. 1: leakage fraction ṁ_y/ṁ_T = μ_заз · f_y ──────────────────
    mdot_leak_fraction = float(np.clip(mu_zaz * f_y, 0.0, 0.5))

    # ── Volumetric efficiency ─────────────────────────────────────────────
    eta_vol = 1.0 - mdot_leak_fraction

    return float(eta_vol), float(mdot_leak_fraction)

