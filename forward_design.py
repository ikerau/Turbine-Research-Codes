#  STATE DICTS for compute_blade_losses
#  Must match the format expected by the off-design script.
# ═══════════════════════════════════════════════════════════════════════════════
def _build_state_dicts(kin, states):
    """
    Build inlet/outlet dicts for stator and rotor in the format
    expected by compute_blade_losses().

    Stator:
      inlet : Pt_rel=Pt0, Tt_rel=Tt0, gamma, R, W=C1 (axial), Cm=C1
      outlet: W=C2, Ps=Ps2, Ts=Ts2, lam_exit=lam_C2

    Rotor:
      inlet : Pt_rel=Pt2_rel, Tt_rel=Tt2_rel, gamma, R, W=W2, Cm, W_theta
      outlet: W=W3, Ps=Ps3, Ts=Ts3, lam_exit=lam_W3
    """
    Tt0 = _mag(kin['Tt0'], 'K')
    Pt0 = _mag(kin['Pt0'], 'Pa')
    Cm  = kin['Cm']

    s_in = {
        "Pt_rel": Q_(Pt0,                'Pa'),
        "Tt_rel": Q_(Tt0,                'K'),
        "Ps":     Q_(states['Ps1'],      'Pa'),
        "Ts":     Q_(states['Ts1'],      'K'),
        "W":      Q_(Cm,                 'm/s'),   # axial inlet
        "Cm":     Q_(Cm,                 'm/s'),
        "C":      Q_(Cm,                 'm/s'),
        "gamma":  states['gamma1'],
        "R":      Q_(states['R1'],       'J/kg/K'),
    }

    s_out = {
        "W":        Q_(kin['C2'],        'm/s'),
        "Ps":       Q_(states['Ps2'],    'Pa'),
        "Ts":       Q_(states['Ts2'],    'K'),
        "Cm":       Q_(Cm,               'm/s'),
        "lam_exit": states['lam_C2'],
        "gamma":    states['gamma2'],
        "R":        Q_(states['R2'],     'J/kg/K'),
        "Pt_rel":   Q_(states['Pt2'],    'Pa'),
        "Tt_rel":   Q_(states['Tt2'],    'K'),
    }

    r_in = {
        "Pt_rel":  Q_(states['Pt2_rel'],   'Pa'),
        "Pt_abs":  Q_(states['Pt2'],       'Pa'),
        "Tt_rel":  Q_(states['Tt2_rel'],   'K'),
        "Ps":      Q_(states['Ps2'],       'Pa'),
        "Ts":      Q_(states['Ts2'],       'K'),
        "W":       Q_(kin['W2'],           'm/s'),
        "Cm":      Q_(Cm,                  'm/s'),
        "C":       Q_(kin['C2'],           'm/s'),
        "W_theta": Q_(kin['W_theta2'],     'm/s'),
        "gamma":   states['gamma2'],
        "R":       Q_(states['R2'],        'J/kg/K'),
    }

    r_out = {
        "W":        Q_(kin['W3'],          'm/s'),
        "Ps":       Q_(states['Ps3'],      'Pa'),
        "Ts":       Q_(states['Ts3'],      'K'),
        "Cm":       Q_(kin['C3'],         'm/s'),
        "lam_exit": states['lam_W3'],
        "gamma":    states['gamma3'],
        "R":        Q_(states['R3'],       'J/kg/K'),
        "Pt_rel":   Q_(states['Pt3_rel'],  'Pa'),
        "Tt_rel":   Q_(states['Tt3_rel'],  'K'),
        "W_theta":  Q_(kin['W_theta3'],    'm/s'),
        "Pt_abs":   Q_(states['Pt3_abs'],   'Pa'),   # already computed in _walk_thermo
        "ht":       Q_(states['hs3'] + 0.5 * kin['C3']**2, 'J/kg'),  # C3=Cm, Cθ3=0
    }

    return s_in, s_out, r_in, r_out


