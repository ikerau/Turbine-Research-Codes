#  MAIN FORWARD DESIGN — IMPULSE VARIANT
# ═══════════════════════════════════════════════════════════════════════════════
def forward_design_impulse(
    kin,
    gas,
    mdot,
    RPM,
    *,
    composition,
    epsilon = 0.5,
    phi_nozzle = 0.975,
    AR_rotor   = 0.60,
    AR_nozzle   = 2.0,
    Z_rotor    = 0.52,
    LE_radius  = None,
    TE_radius  = None,
    tip_gap    = None,
    tip_percent    = None,
    tol        = 1e-6,
    max_iter   = 100,
    verbose    = True,
):
    """
    Forward design for a partial-admission supersonic impulse turbine.

    Required:
        composition : Cantera composition string
        N_nozzles   : number of active CD nozzle passages

    Optional:
        phi_nozzle  : nozzle velocity coefficient (0.975)
        AR_rotor    : rotor aspect ratio (span/Cax)
        Z_rotor     : rotor Zweifel target
        LE_radius   : leading-edge radius for blockage (default 0.005 in)
        TE_radius   : trailing-edge radius for blockage (default 0.0025 in)
        tip_gap     : default 0.25 mm

    kin must come from design_point_kinematics(..., impulse=True).
    """
    if not kin.get("impulse", False):
        raise ValueError("forward_design_impulse requires kin built with "
                         "design_point_kinematics(..., impulse=True).")

    LE_radius = LE_radius or Q_(0.005,  'inch')
    TE_radius = TE_radius or Q_(0.0025, 'inch')
    
    mdot_kg   = _mag(mdot, 'kg/s')
    kin['mdot_kg'] = mdot_kg

    r_loss_s  = 1.0
    r_loss_r  = 1.0
    converged = False
    states = annulus = nozzle = rotor = loss_s = loss_r = perf = None
    err = 1e6
    for outer in range(max_iter):
        
        gas.TPX = _mag(kin['Tt0'], 'K'), _mag(kin['Pt0'], 'Pa'), composition
        states  = _walk_thermo(kin, gas, r_loss_s, r_loss_r)

        annulus = _size_annulus_impulse(kin, states, mdot_kg, epsilon,
                                 stator_blade=nozzle,
                                 rotor_blade=rotor)

        nozzle = _build_nozzle_geometry(kin, states, annulus, mdot_kg,
                                         LE_radius, TE_radius, AR_nozzle)

        rotor = _build_rotor_geometry_impulse(kin, states, annulus,
                                       AR_rotor, Z_rotor, tip_gap,
                                       LE_radius, TE_radius,
                                       r_loss_r=r_loss_r, tip_percent=tip_percent)

        s_in, s_out, r_in, r_out = _build_state_dicts(kin, states)
        r_in['Pt0_stage'] = kin['Pt0']   # stage inlet total pressure

        loss_s = compute_blade_losses_fixed_phi(
            nozzle, s_in, s_out, gas, rpm=Q_(0, 'rpm'), phi=phi_nozzle)
        loss_r = compute_blade_losses_impulse(
            rotor,  r_in, r_out, gas, rpm=RPM)
        
        """
        print(f"zeta_l   = {loss_r['zeta_l']:.5f}")
        print(f"span     = {float((rotor['R_o_outlet'] - rotor['R_i_outlet']).to('mm').magnitude):.4f} mm")
        print(f"tip_gap  = {float(rotor['Tip_Gap'].to('mm').magnitude):.4f} mm")
        print(f"tau/h    = {float((rotor['Tip_Gap'] / (rotor['R_o_outlet'] - rotor['R_i_outlet'])).to('').magnitude)*100:.2f} %")
        print(f"Pt_in    = {float(r_in['Pt_rel'].to('Pa').magnitude):.1f} Pa")
        print(f"Ps2      = {float(r_out['Ps'].to('Pa').magnitude):.1f} Pa")"""
        
        
        r_loss_s_new = float(loss_s['r_loss_new'])
        r_loss_r_new = float(loss_r['r_loss_new'])

        alpha    = 0.3
        r_loss_s = alpha * r_loss_s_new + (1.0 - alpha) * r_loss_s
        r_loss_r = alpha * r_loss_r_new + (1.0 - alpha) * r_loss_r

        err = max(abs(r_loss_s_new - r_loss_s),
                  abs(r_loss_r_new - r_loss_r))

        perf = _compute_eta(kin, states, gas, composition=composition)
        eta_vol, mdot_leak = eta_volumetric_ovsyannikov(
            rotor, kin, states, phi_nozzle=phi_nozzle
        )
        perf['mdot_leak_frac'] = mdot_leak
        perf['eta_vol'] = eta_vol

        if verbose:
            print(f"  iter {outer+1:2d}  |  "
                  f"r_s={r_loss_s:.6f}  r_r={r_loss_r:.6f}  |  "
                  f"err={err:.2e}  |  "
                  f"η_full={perf['eta_ts']*100:.2f}%  "
                  f"PR={perf['Pt_ratio']:.4f}")

        if err < tol:
            converged = True
            break

    if not converged and verbose:
        print(f"  ⚠  forward_design_impulse did not converge in "
              f"{max_iter} iterations (err={err:.2e})")

    # Partial-admission correction
    D_turb_m      = 2.0 * kin['Rm']
    rotor_pitch_m = (2.0 * np.pi * kin['Rm']) / rotor['Blade_N']
    RPM_mag       = float(RPM.to('rpm').magnitude)
    f_arc_m       = nozzle['_f_arc_m']

    adm = partial_admission_correction(
        eta_ts      = perf['eta_ts'],
        U           = kin['U'],
        C2          = kin['C2'],
        C3          = kin['C3'],
        Ps_rotor_in = states['Ps2'],
        Ts_rotor_in = states['Ts2'],
        R_rotor_in  = states['R2'],
        rotor_pitch = rotor_pitch_m,
        f_arc       = f_arc_m,
        D_turb      = D_turb_m,
        RPM         = RPM_mag,
    )
    perf['eta_ts_blade']  = perf['eta_ts'] 
    perf['eta_partial']   = adm['eta_partial'] * eta_vol
    perf['eta_ts']        = perf['eta_partial'] 

    perf.update(dict(
        r_loss_s      = r_loss_s,
        r_loss_r      = r_loss_r,
        hub_tip       = annulus['stator_exit']['hub_tip'],
        Rm_mm         = kin['Rm'] * 1000,
        U_ms          = kin['U'],
        Cm_ms         = kin['Cm'],
        C3_ms         = kin['C3'],
        alpha3_deg    = kin['alpha3'],
        eta_full      = adm['eta_full'],
        eta_partial   = adm['eta_partial'],
        admission_eps = adm['admission_eps'],
        sector_factor = adm['sector_factor'],
        windage       = adm['windage'],
        VR            = adm['VR'],
        K_ratio       = adm['K'],
        f_arc_m       = adm['f_arc_m'],
    ))

    if verbose:
        _print_design_summary_impulse(kin, states, annulus, nozzle, rotor,
                                       perf, loss_s, loss_r, adm)

    return dict(
        stator    = nozzle,
        rotor     = rotor,
        states    = states,
        annulus   = annulus,
        perf      = perf,
        losses    = dict(stator=loss_s, rotor=loss_r),
        admission = adm,
        converged = converged,
    )


