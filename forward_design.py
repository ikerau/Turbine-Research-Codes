def design_point_kinematics(
    *, Tt0, Pt0, gas, mdot, RPM, psi, phi,
    W_t=None, PR_tt=None, eta_tt=None,
    impulse=False,
):
    """
    Returns kinematic dict with inlet_gas, U, Rm, Cm, velocity triangles.
 
    Parameters
    ----------
    impulse : bool
        If True, build exit triangle for a symmetric impulse rotor:
            |W3|     = |W2|        (Cm constant, |W_θ| conserved)
            W_θ3     = W_θ2        (magnitude, positive)
            |β3|     = |β2|        (magnitude, positive from arctan2)
            C_θ3     = W_θ3 − U    (signed: positive = same direction as U)
            C3, α3  falls out of the exit triangle
        If False (default), use the standard axial-flow convention
        Cθ3 = 0 → W_θ3 = U, C3 = Cm, α3 = 0.
    """
    if (W_t is None) == (PR_tt is None):
        raise ValueError("Provide exactly one of W_t or PR_tt.")
    if PR_tt is not None and eta_tt is None:
        raise ValueError("eta_tt required when PR_tt is supplied.")
 
    # ── Gas properties ────────────────────────────────────────────────────────
    gas.TP = _mag(Tt0, 'K'), _mag(Pt0, 'Pa')
    Cp    = float(gas.cp_mass)
    gamma = float(gas.cp_mass / gas.cv_mass)
    R     = float(ct.gas_constant / gas.mean_molecular_weight)
    mu    = float(gas.viscosity)
    inlet_gas = dict(gamma=gamma, R=R, Cp=Cp, mu=mu)
 
    # ── Specific work ─────────────────────────────────────────────────────────
    Tt0_K  = _mag(Tt0, 'K')
    if W_t is not None:
        delta_H = _mag(W_t, 'W') / _mag(mdot, 'kg/s')
        source  = 'W_t'
    else:
        gm1_g   = (gamma - 1.0) / gamma
        delta_H = eta_tt * Cp * Tt0_K * (1.0 - (1.0 / PR_tt) ** gm1_g)
        source  = 'PR_tt'
 
    # ── Kinematics — inlet triangle (identical for both cases) ────────────────
    omega    = _mag(RPM.to('rad/s'), 'rad/s')
    U        = np.sqrt(delta_H / psi)
    Rm       = U / omega
    Cm       = phi * U
    C_theta2 = delta_H / U
    C2       = np.sqrt(Cm**2 + C_theta2**2)
    alpha2   = np.degrees(np.arctan2(C_theta2, Cm))
    W_theta2 = C_theta2 - U                             # positive for loaded turbine
    W2       = np.sqrt(Cm**2 + W_theta2**2)
    beta2    = np.degrees(np.arctan2(W_theta2, Cm))
 
    # ── Exit triangle — depends on stage type ────────────────────────────────
    if impulse:
        # Symmetric rotor: |W3|=|W2|, W_θ3 = W_θ2 (same positive magnitude)
        W_theta3 = W_theta2
        W3       = W2
        beta3    = beta2
        # Signed C_θ3 using the same rule as the inlet: C_θ = W_θ − U
        C_theta3 = W_theta3 - U                         # can be + or −
        C3       = np.sqrt(Cm**2 + C_theta3**2)
        alpha3   = np.degrees(np.arctan2(C_theta3, Cm))
    else:
        # Standard axial exit: C_θ3 = 0 → W_θ3 = U, C3 = Cm, α3 = 0
        W_theta3 = U
        W3       = np.sqrt(Cm**2 + W_theta3**2)
        beta3    = np.degrees(np.arctan2(W_theta3, Cm))
        C_theta3 = 0.0
        C3       = Cm
        alpha3   = 0.0
 
    R_rxn = 1.0 - psi / 2.0   # nominal reaction — diagnostic when impulse=True
 
    return dict(
        inlet_gas=inlet_gas, delta_H=delta_H,
        U=U, Rm=Rm, Cm=Cm, omega=omega,
        psi=psi, phi=phi, source=source,
        impulse=impulse,                                 # stored for downstream
        C2=C2, C_theta2=C_theta2, alpha2=alpha2,
        W2=W2, W_theta2=W_theta2, beta2=beta2,
        W3=W3, W_theta3=W_theta3, beta3=beta3,
        C3=C3, C_theta3=C_theta3, alpha3=alpha3,         # NEW keys
        R_rxn=R_rxn,
        Tt0=Tt0, Pt0=Pt0,
        mdot_kg=mdot.to('kg/s').magnitude,
    )


# ═══════════════════════════════════════════════════════════════════════════════
#  THERMODYNAMIC WALK
#  Given kinematic velocities + loss ratios, compute all station static states.
#  All velocities are FIXED by psi/phi; only pressures/temperatures change.
# ═══════════════════════════════════════════════════════════════════════════════
def _walk_thermo(kin, gas, r_loss_s, r_loss_r):

    Tt0  = _mag(kin['Tt0'], 'K')
    Pt0  = _mag(kin['Pt0'], 'Pa')
    Cm   = kin['Cm']
    C2   = kin['C2']
    W2   = kin['W2']
    W3   = kin['W3']
    C3   = kin['C3']

    gamma0 = kin['inlet_gas']['gamma']
    R0     = kin['inlet_gas']['R']
    Cp0    = kin['inlet_gas']['Cp']

    def _iter_static(T_seed, P, gamma_seed, R_seed, max_it=15):
        gamma_i, R_i = gamma_seed, R_seed
        T_i = T_seed
        for _ in range(max_it):
            gas.TP = T_i, P
            g_new  = float(gas.cp_mass / gas.cv_mass)
            R_new  = float(ct.gas_constant / gas.mean_molecular_weight)
            Cp_i   = float(gas.cp_mass)
            if abs(g_new - gamma_i) < 1e-7 and abs(R_new - R_i) < 1e-7:
                break
            gamma_i, R_i = g_new, R_new
        return g_new, R_new, Cp_i, float(gas.density), float(gas.enthalpy_mass), float(gas.viscosity)

    def _lam_from_velocity(V, Tt, gamma, R):
        a_c = np.sqrt(2 * gamma / (gamma + 1) * R * Tt)
        return V / a_c

    def _static_from_lam(lam, Tt, Pt, gamma):
        gm1_gp1 = (gamma - 1.0) / (gamma + 1.0)
        Ts = Tt * (1.0 - gm1_gp1 * lam**2)
        Ps = Pt * (1.0 - gm1_gp1 * lam**2) ** (gamma / (gamma - 1.0))
        return Ts, Ps

    def _lam_polytropic(V, Tt, Pt_in, Pt_out, gamma, R):
        """
        Compute lam mirroring blade_passage_new:
        1. Derive Ps from kinematic V and Tt (using Pt_out for static)
        2. Compute n_poly from Pt_in/Ps and Pt_out/Ps
        3. Recompute lam from polytropic relation using Pt_in
        Iterate until gamma converges.
        """
        gamma_i, R_i = gamma, R

        for _ in range(20):
            # Step 1: get Ps from kinematic velocity and exit total pressure
            lam_kin  = _lam_from_velocity(V, Tt, gamma_i, R_i)
            Ts, Ps   = _static_from_lam(lam_kin, Tt, Pt_out, gamma_i)

            # Step 2: n_poly from Pt_in, Pt_out, Ps — same as blade_passage_new
            gm1_g          = (gamma_i - 1.0) / gamma_i
            Pt_in_over_Ps  = Pt_in  / Ps
            Pt_out_over_Ps = Pt_out / Ps
            if Pt_in_over_Ps <= 1.0 or Pt_out_over_Ps <= 1.0:
                # No expansion — subsonic with negligible loss
                lam_poly = lam_kin
                break
            n_poly = 1.0 / (1.0 - gm1_g * (
                        np.log(Pt_out_over_Ps) / np.log(Pt_in_over_Ps)))

            # Step 3: lam from polytropic relation using Pt_in
            omn_n    = (1.0 - n_poly) / n_poly
            gp1_gm1  = (gamma_i + 1.0) / (gamma_i - 1.0)
            lam_poly = float(np.sqrt(np.clip(
                            gp1_gm1 * (1.0 - Pt_in_over_Ps ** omn_n),
                            0.0, None)))

            # Update Ts and Ps with polytropic lam
            Ts, Ps = _static_from_lam(lam_poly, Tt, Pt_out, gamma_i)

            # Update gamma at new static conditions
            g_new, R_new, *_ = _iter_static(Ts, Ps, gamma_i, R_i)
            if abs(g_new - gamma_i) < 1e-7:
                gamma_i, R_i = g_new, R_new
                break
            gamma_i, R_i = g_new, R_new

        return lam_poly, Ts, Ps, gamma_i, R_i

    # ── Station 1: stator inlet ───────────────────────────────────────────
    gamma_i, R_i = gamma0, R0
    for _ in range(20):
        lam1     = _lam_from_velocity(Cm, Tt0, gamma_i, R_i)
        Ts1, Ps1 = _static_from_lam(lam1, Tt0, Pt0, gamma_i)
        g_new, R_new, Cp1, rho1, hs1, mu1 = _iter_static(Ts1, Ps1, gamma_i, R_i)
        if abs(g_new - gamma_i) < 1e-7:
            break
        gamma_i, R_i = g_new, R_new
    gamma1, R1 = g_new, R_new

    # ── Station 2: stator exit ────────────────────────────────────────────
    Tt2  = Tt0
    Pt2  = r_loss_s * Pt0

    lam_C2, Ts2, Ps2, gamma2, R2 = _lam_polytropic(
        C2, Tt2, Pt0, Pt2, gamma1, R1)

    g_new, R_new, Cp2, rho2, hs2, mu2 = _iter_static(Ts2, Ps2, gamma2, R2)
    gamma2, R2 = g_new, R_new
    M_C2 = lambda_to_mach(lam_C2, gamma2)

    # ── Rotor inlet (relative frame) ──────────────────────────────────────
    Tt2_rel  = Ts2 + W2**2 / (2.0 * Cp2)
    ht2_rel  = hs2 + 0.5 * W2**2
    lam_W2   = _lam_from_velocity(W2, Tt2_rel, gamma2, R2)
    p_rat_w2 = (1.0 - (gamma2-1.0)/(gamma2+1.0) * lam_W2**2) \
               ** (gamma2 / (gamma2 - 1.0))
    Pt2_rel  = Ps2 / p_rat_w2
    M_W2     = lambda_to_mach(lam_W2, gamma2)

    # ── Station 3: rotor exit ─────────────────────────────────────────────
    # Rothalpy conserved: ht3_rel = ht2_rel
    # Derive Tt3_rel from W3 and hs3:
    # hs3 = ht2_rel - 0.5*W3^2  (from rothalpy)
    # Tt3_rel = Ts3 + W3^2/(2*Cp3)
    # Iterate to find Ts3 consistent with hs3_target

    hs3_target = ht2_rel - 0.5 * W3**2
    Pt3_rel    = r_loss_r * Pt2_rel

    # Seed Ts3 from Cp2
    Ts3 = Ts2 + (hs3_target - hs2) / Cp2

    for _ in range(30):
        gas.TP   = Ts3, Ps2   # rough pressure seed
        hs3_can  = float(gas.enthalpy_mass)
        Cp3_i    = float(gas.cp_mass)
        dT       = (hs3_target - hs3_can) / Cp3_i
        Ts3     += dT
        Ts3      = Ts3
        if abs(dT) < 1e-6:
            break

    Tt3_rel = Ts3 + W3**2 / (2.0 * Cp3_i)

    # Now use _lam_polytropic for rotor exit — Pt_in = Pt2_rel
    lam_W3, Ts3, Ps3, gamma3, R3 = _lam_polytropic(
        W3, Tt3_rel, Pt2_rel, Pt3_rel, gamma2, R2)

    g_new, R_new, Cp3, rho3, hs3, mu3 = _iter_static(Ts3, Ps3, gamma3, R3)
    gamma3, R3 = g_new, R_new
    M_W3       = lambda_to_mach(lam_W3, gamma3)

    # Recompute Tt3_rel and Pt3_rel at converged state
    Tt3_rel  = Ts3 + W3**2 / (2.0 * Cp3)
    lam_W3   = _lam_from_velocity(W3, Tt3_rel, gamma3, R3)
    p_rat_w3 = (1.0 - (gamma3-1.0)/(gamma3+1.0) * lam_W3**2) \
               ** (gamma3 / (gamma3 - 1.0))
    Ps3      = Pt3_rel * p_rat_w3

    # ── Absolute exit ─────────────────────────────────────────────────────
    Tt3_abs  = Ts3 + C3**2 / (2.0 * Cp3)
    lam_C3   = _lam_from_velocity(C3, Tt3_abs, gamma3, R3)
    p_rat_c3 = (1.0 - (gamma3-1.0)/(gamma3+1.0) * lam_C3**2) \
               ** (gamma3 / (gamma3 - 1.0))
    Pt3_abs  = Ps3 / p_rat_c3

    return dict(
        Ts1=Ts1, Ps1=Ps1, rho1=rho1, Cp1=Cp1, gamma1=gamma1, R1=R1, mu1=mu1,
        lam_C1=lam1,
        Ts2=Ts2, Ps2=Ps2, rho2=rho2, Cp2=Cp2, gamma2=gamma2, R2=R2, mu2=mu2,
        Tt2=Tt2, Pt2=Pt2, lam_C2=lam_C2, M_C2=M_C2, hs2=hs2,
        Tt2_rel=Tt2_rel, Pt2_rel=Pt2_rel, lam_W2=lam_W2, M_W2=M_W2,
        ht2_rel=ht2_rel,
        Ts3=Ts3, Ps3=Ps3, rho3=rho3, Cp3=Cp3, gamma3=gamma3, R3=R3, mu3=mu3,
        Tt3_rel=Tt3_rel, Pt3_rel=Pt3_rel, lam_W3=lam_W3, M_W3=M_W3,
        Tt3_abs=Tt3_abs, Pt3_abs=Pt3_abs, lam_C3=lam_C3,
        hs3=hs3,
        n_poly_s = 1.0 / (1.0 - (gamma2-1.0)/gamma2 * (
                    np.log(Pt2/Ps2) / np.log(Pt0/Ps2))),
        n_poly_r = 1.0 / (1.0 - (gamma3-1.0)/gamma3 * (
                    np.log(Pt3_rel/Ps3) / np.log(Pt2_rel/Ps3))),
    )

# ═══════════════════════════════════════════════════════════════════════════════
#  ANNULUS SIZING
#  A = mdot / (rho * Cm)
#  Rm fixed → Ro = sqrt(Rm² + A/(2π)),  Ri = sqrt(Rm² - A/(2π))
# ═══════════════════════════════════════════════════════════════════════════════
def _size_annulus(kin, states, mdot_kg, stator_blade=None, rotor_blade=None):
    Rm = kin['Rm']
    Cm = kin['Cm']

    Rm = kin['Rm']   # FIXED — never changes
    Cm = kin['Cm']

    def _radii(rho, blockage=0.0):
        A_flow = mdot_kg / (rho * Cm)
        A_phys = A_flow / (1.0 - blockage)
        half   = A_phys / (2 * np.pi)
        Ro_sq  = Rm**2 + half
        Ri_sq  = Rm**2 - half
        if Ri_sq <= 0:
            raise ValueError(f"Annulus infeasible: Ri² = {Ri_sq:.4e}")
        Ro   = np.sqrt(Ro_sq)
        Ri   = np.sqrt(Ri_sq)
        span = Ro - Ri
        return dict(A=A_phys, A_flow=A_flow, Ro=Ro, Ri=Ri, span=span, hub_tip=Ri/Ro)

    def _blockage(blade, is_le):
        if blade is None:
            return 0.0
        r     = blade['LE_radius'] if is_le else blade['TE_radius']
        d     = float(r.to('m').magnitude) * 2
        pitch = 2 * np.pi * Rm / blade['Blade_N']   # pitch at Rm — consistent
        return d / pitch

    # ── Iterate blockage ──────────────────────────────────────────────────
    ann1  = _radii(states['rho1'])
    ann2  = _radii(states['rho2'])
    ann2r = _radii(states['rho2'])
    ann3  = _radii(states['rho3'])

    for _ in range(10):
        b_le_s = _blockage(stator_blade, is_le=True)
        b_te_s = _blockage(stator_blade, is_le=False)
        b_le_r = _blockage(rotor_blade,  is_le=True)
        b_te_r = _blockage(rotor_blade,  is_le=False)

        ann1_new  = _radii(states['rho1'], b_le_s)
        ann2_new  = _radii(states['rho2'], b_te_s)
        ann2r_new = _radii(states['rho2'], b_le_r)
        ann3_new  = _radii(states['rho3'], b_te_r)

        err = max(
            abs(ann1_new['Ro']  - ann1['Ro']),
            abs(ann2_new['Ro']  - ann2['Ro']),
            abs(ann2r_new['Ro'] - ann2r['Ro']),
            abs(ann3_new['Ro']  - ann3['Ro']),
        )

        ann1, ann2, ann2r, ann3 = ann1_new, ann2_new, ann2r_new, ann3_new

        if err < 1e-9:
            break

    return dict(
        stator_inlet = ann1,
        stator_exit  = ann2,
        rotor_inlet  = ann2r,
        rotor_exit   = ann3,
    )


# ═══════════════════════════════════════════════════════════════════════════════
#  BLADE GEOMETRY
#  Given flow angles, annulus dimensions, AR, and Zweifel targets:
#    1. Chord_ax from AR
#    2. N from Zweifel
#    3. Throat from Q-function (continuity-consistent)
#    4. Deviation loop → converge metal exit angle
#    5. Build Pritchard profile → extract stagger
# ═══════════════════════════════════════════════════════════════════════════════
def _q_func(lam, gamma):
    gm1 = gamma - 1.0
    gp1 = gamma + 1.0
    return lam * (gp1 / 2.0 * (1 - (gm1 / gp1) * lam**2)) ** (1.0 / gm1)


def _delta_from_geometry(o_m, pitch_m, lam, lam_crit):
    """
    Deviation magnitude delta using the same smoothstep as off_design.deviation().
    Returns delta such that: alpha_out = arccos(o/t) - delta
    """
    sinb = float(np.clip(o_m / pitch_m, 0.0, 1.0))
    beta_g_circ = np.degrees(np.arcsin(sinb))

    arg = sinb * (1.0 + (1.0 - sinb) * (beta_g_circ / 90.0)**2)
    arg = float(np.clip(arg, -1.0, 1.0))
    delta_0 = np.degrees(np.arcsin(arg)) - beta_g_circ

    lam_ratio = lam / lam_crit if lam_crit > 0 else 0.0
    if lam_ratio <= 0.5:
        return delta_0
    elif lam_ratio < 1.0:
        X = 2.0 * lam_ratio - 1.0
        return delta_0 * (1.0 - 10*X**3 + 15*X**4 - 6*X**5)
    else:
        return 0.0

def _build_blade_geometry(
    kin, states, annulus,
    AR_stator, AR_rotor,
    Z_stator, Z_rotor,
    LE_radius, TE_radius,
    inlet_wedge, exit_wedge_s, exit_wedge_r,
    zeta_ung_s, zeta_ung_r,
    tip_gap, tip_gap_stator,
    t_s_rotor,
    t_s_stator,
    r_loss_s=1.0, r_loss_r=1.0,
    build_pritchard=True,
):
    """
    Build stator and rotor blade geometry dicts.

    Deviation handling
    ------------------
    Subsonic  (lam_exit < lam_crit):
        Iterate beta2_metal via _delta_from_geometry until
        beta2_flow_actual = beta2_flow_target.

    Supersonic (lam_exit >= lam_crit):
        o is pinned by mass-flow continuity at the throat — never changes.
        Required exit area A_exit is back-calculated from the target flow
        angle via the sup_deviation mass-conservation equation:

            cos(alpha_target) = mdot*sqrt(Tt) / (mf_term * Pt * A_exit * q(lam))
            => A_exit_required = mdot*sqrt(Tt) / (mf_term * Pt * q(lam) * cos(alpha_target))

        beta2_metal is then found with brentq so that axial_exit_area_nb(blade)
        equals A_exit_required. The lower bracket is beta2_geometric =
        arccos(o/pitch) — the passage cannot be tighter than the throat.
        At convergence: beta2_metal > beta2_flow_actual (metal is more closed
        than the flow angle, as expected for supersonic expansion).
    """
    Rm      = kin['Rm']
    mdot_kg = kin['mdot_kg']
    TE_m    = _mag(TE_radius, 'm')
    inlet_wedge  = inlet_wedge  or Q_(15.0, 'deg')
    results = {}

    for row_name, is_rotor in [('stator', False), ('rotor', True)]:

        # ── Row-specific unpacking ────────────────────────────────────────
        if not is_rotor:
            ann_in     = annulus['stator_inlet']
            ann_out    = annulus['stator_exit']
            if t_s_stator is None:
                tip_gap_blade = tip_gap_stator
            else:
                avg_span      = 0.5 * (ann_out['span'] + ann_in['span'])
                tip_gap_blade = Q_(avg_span * t_s_stator, 'm')
            AR         = AR_stator
            Z_tgt      = Z_stator
            beta1_flow = 0.0
            beta2_flow = kin['alpha2']
            lam_exit   = states['lam_C2']
            gamma_exit = states['gamma2']
            R_exit     = states['R2']
            Ps_exit    = states['Ps2']
            Pt_row     = float(kin['Pt0'].to('Pa').magnitude)
            Tt_row     = float(kin['Tt0'].to('K').magnitude)
            r_loss     = r_loss_s
            exit_wedge = exit_wedge_s
            zeta_ung   = zeta_ung_s
        else:
            ann_in     = annulus['rotor_inlet']
            ann_out    = annulus['rotor_exit']
            if t_s_rotor is None:
                tip_gap_blade = tip_gap
            else:
                avg_span      = 0.5 * (ann_out['span'] + ann_in['span'])
                tip_gap_blade = Q_(avg_span * t_s_rotor, 'm')
            AR         = AR_rotor
            Z_tgt      = Z_rotor
            beta1_flow = abs(kin['beta2'])
            beta2_flow = kin['beta3']
            lam_exit   = states['lam_W3']
            gamma_exit = states['gamma3']
            R_exit     = states['R3']
            Ps_exit    = states['Ps3']
            Pt_row     = states['Pt2_rel']
            Tt_row     = states['Tt2_rel']
            r_loss     = r_loss_r
            exit_wedge = exit_wedge_r
            zeta_ung   = zeta_ung_r

        span_in  = ann_in['span']
        span_out = ann_out['span']
        Ro_in    = ann_in['Ro'];  Ri_in  = ann_in['Ri']
        Ro_out   = ann_out['Ro']; Ri_out = ann_out['Ri']

        # ── Chord from aspect ratio ───────────────────────────────────────
        Cax = span_out / AR

        # ── Blade count from Zweifel ──────────────────────────────────────
        tb1   = np.tan(np.radians(beta1_flow))
        tb2   = np.tan(np.radians(beta2_flow))
        cb2   = np.cos(np.radians(beta2_flow))
        pitch = Z_tgt * Cax / (2.0 * (tb1 + tb2) * cb2**2)
        N     = max(int(round(2 * np.pi * Rm / pitch)), 3)
        pitch = 2 * np.pi * Rm / N

        # ── Polytropic exponent ───────────────────────────────────────────
        Pt_out = Pt_row * r_loss
        gm1    = gamma_exit - 1.0
        gp1    = gamma_exit + 1.0
        if Pt_row / Ps_exit > 1.0 and Pt_out / Ps_exit > 1.0 and r_loss < 1.0:
            n_over_nm1 = ((gamma_exit / gm1)
                          * np.log(Pt_row / Ps_exit)
                          / np.log(Pt_out / Ps_exit))
            n_poly = float(np.clip(n_over_nm1 / (n_over_nm1 - 1.0),
                                   1.01, gamma_exit))
        else:
            n_poly = gamma_exit

        lam_crit_val = lam_crit_polytropic(n_poly, gamma_exit)

        # ── Mass flow function ────────────────────────────────────────────
        mf_term = np.sqrt((gamma_exit / R_exit) * (2.0 / gp1) ** (gp1 / gm1))

        # ── Inlet metal angle ─────────────────────────────────────────────
        beta1_metal = beta1_flow

        # =====================================================================
        # THROAT AND METAL ANGLE
        # =====================================================================

        if lam_exit >= lam_crit_val:
            # ── SUPERSONIC / CHOKED ──────────────────────────────────────────
            #
            # Step 1: pin o from mass-flow continuity at critical conditions.
            A_throat_total = (mdot_kg * np.sqrt(Tt_row)) / (mf_term * Pt_row)
            o = A_throat_total / (N * span_out)
            if o > pitch:
                N     = max(int(np.floor(
                            A_throat_total / (0.95 * span_out * pitch))), 3)
                pitch = 2 * np.pi * Rm / N
                o     = A_throat_total / (N * span_out)
            o = max(o, 1e-5)

            # Step 2: geometric lower bound for beta2_metal
            beta2_geometric = np.degrees(np.arccos(np.clip(o / pitch, 0.0, 1.0)))

            # Step 3: back-calculate A_exit_required from target flow angle.
            # From sup_deviation:
            #   cos(alpha) = mdot*sqrt(Tt) / (mf_term * Pt * A_exit * q_n(lam))
            q_n_out         = q_n_func(lam_exit, n_poly, gamma_exit)
            cos_alpha_tgt   = np.cos(np.radians(beta2_flow))
            A_exit_required = (mdot_kg * np.sqrt(Tt_row)) / \
                               (mf_term * Pt_row * q_n_out * cos_alpha_tgt)

            # Step 4: find beta2_metal via brentq so axial_exit_area_nb = A_exit_required.
            def _make_tmp(b2m):
                return {
                    'Beta_1':     Q_(beta1_metal, 'deg'),
                    'Beta_2':     Q_(b2m,         'deg'),
                    'throat':     Q_(o,            'm'),
                    'Blade_N':    N,
                    'Chord_ax':   Q_(Cax,          'm'),
                    'R_o_outlet': Q_(Ro_out,       'm'),
                    'R_i_outlet': Q_(Ri_out,       'm'),
                    'R_o_inlet':  Q_(Ro_in,        'm'),
                    'R_i_inlet':  Q_(Ri_in,        'm'),
                    'inlet_wedge': inlet_wedge,
                    'exit_wedge': exit_wedge,
                    'zeta_ung':   zeta_ung,
                    'TE_radius':  TE_radius,
                    'LE_radius':  LE_radius,
                    'stagger':    Q_(np.degrees(np.arctan(
                                      (np.tan(np.radians(beta1_metal))
                                       + np.tan(np.radians(b2m))) / 2.0)),
                                      'deg'),
                    'rotating':   is_rotor,
                }

            def area_residual(b2m):
                A = float(axial_exit_area_nb(_make_tmp(b2m)).to('m**2').magnitude)
                return A - A_exit_required

            try:
                lo   = beta2_geometric
                hi   = 89.0
                f_lo = area_residual(lo)
                f_hi = area_residual(hi)
                if f_lo * f_hi < 0.0:
                    beta2_metal = brentq(area_residual, lo, hi, xtol=1e-4)
                else:
                    # A_exit_required outside achievable range — use geometric
                    beta2_metal = beta2_geometric
            except Exception:
                beta2_metal = beta2_geometric

            # Step 5: verify with sup_deviation
            blade_tmp         = _make_tmp(beta2_metal)
            beta2_flow_actual = float(sup_deviation(
                blade_tmp, lam_exit,
                Pt_row, Tt_row,
                gamma_exit, R_exit, n_poly,
            ).to('deg').magnitude)

            # Physical check: metal should be more closed than flow
            # (beta2_metal > beta2_flow_actual for supersonic expansion)
            delta_final = beta2_metal - beta2_flow_actual

        else:
            # ── SUBSONIC ─────────────────────────────────────────────────────
            # Iterate beta2_metal via _delta_from_geometry until converged.
            beta2_metal = beta2_flow

            for dev_iter in range(40):
                o_current = pitch * np.cos(np.radians(beta2_metal))
                o_current = max(o_current, 1e-5)

                delta = _delta_from_geometry(
                    o_current, pitch, lam_exit, lam_crit_val)

                beta2_metal_new = beta2_flow + delta

                if abs(beta2_metal_new - beta2_metal) < 0.005:
                    beta2_metal = beta2_metal_new
                    o           = o_current
                    break

                beta2_metal = beta2_metal_new
                o           = o_current
            else:
                o = pitch * np.cos(np.radians(beta2_metal))

            o = max(o, 1e-5)

            Mw2               = lambda_to_mach(lam_exit, gamma_exit)
            alpha_out_val     = float(deviation_raw(
                o, pitch, Mw2, gamma_exit, 1.0).to('deg').magnitude)
            delta_final       = beta2_metal - alpha_out_val
            beta2_flow_actual = alpha_out_val

        # ── Span at throat ────────────────────────────────────────────────
        ew_rad      = float(exit_wedge.to('rad').magnitude)
        zeta_rad    = float(zeta_ung.to('rad').magnitude)
        bout_rad    = np.radians(beta2_metal)
        beta_2_p    = bout_rad - ew_rad + zeta_rad
        x_2         = Cax - TE_m + (o + TE_m) * np.sin(beta_2_p)
        x_frac      = float(np.clip(x_2 / Cax, 0.0, 1.0))
        span_throat = span_in + x_frac * (span_out - span_in)

        # ── Stagger ───────────────────────────────────────────────────────
        if build_pritchard:
            try:
                params = dict(
                    LE_radius   = LE_radius,
                    TE_radius   = TE_radius,
                    Chord_ax    = Q_(Cax,              'm'),
                    zeta_ung    = zeta_ung,
                    beta_in     = Q_(beta1_metal,      'deg'),
                    beta_out    = Q_(-abs(beta2_metal), 'deg'),
                    inlet_wedge = inlet_wedge,
                    exit_wedge  = exit_wedge,
                    N_blades    = N,
                    throat      = Q_(o,                'm'),
                    Radius      = Q_(Rm,               'm'),
                )
                _, _, _, extra = build_pritchard_profile(params, n=40)
                stagger_rad = extra['stagger_angle']
            except Exception:
                stagger_rad = np.arctan(
                    (np.tan(np.radians(beta1_metal))
                     + np.tan(np.radians(beta2_metal))) / 2.0)
        else:
            stagger_rad = np.arctan(
                (np.tan(np.radians(beta1_metal))
                 + np.tan(np.radians(beta2_metal))) / 2.0)

        # ── Assemble blade dict ───────────────────────────────────────────
        blade = {
            "Beta_1":     Q_(beta1_metal,             'deg'),
            "Beta_2":     Q_(beta2_metal,             'deg'),
            "stagger":    Q_(np.degrees(stagger_rad), 'deg'),
            "throat":     Q_(o,                       'm'),
            "TE_radius":  TE_radius,
            "LE_radius":  LE_radius,
            "Chord_ax":   Q_(Cax,                     'm'),
            "Blade_N":    N,
            "Tip_Gap":    tip_gap_blade,
            "R_o_inlet":  Q_(Ro_in,                   'm'),
            "R_i_inlet":  Q_(Ri_in,                   'm'),
            "R_o_outlet": Q_(Ro_out,                  'm'),
            "R_i_outlet": Q_(Ri_out,                  'm'),
            "rotating":   is_rotor,
            "inlet_wedge": inlet_wedge,
            "exit_wedge": exit_wedge,
            "zeta_ung":   zeta_ung,
            # ── Diagnostics ──────────────────────────────────────────────
            "_throat_mm":          o * 1000,
            "_pitch_mm":           pitch * 1000,
            "_Cax_mm":             Cax * 1000,
            "_span_mm":            span_out * 1000,
            "_span_throat_mm":     span_throat * 1000,
            "_N":                  N,
            "_n_poly":             n_poly,
            "_lam_crit":           lam_crit_val,
            "_lam_exit":           lam_exit,
            "_supersonic":         lam_exit >= lam_crit_val,
            "_deviation":          float(delta_final),
            "_beta2_flow_actual":  float(beta2_flow_actual),
            "_beta2_flow_target":  float(beta2_flow),
            "_beta2_metal":        float(beta2_metal),
            "_beta2_geometric":    float(beta2_geometric) if lam_exit >= lam_crit_val else float(beta2_metal),
            "_stagger_deg":        np.degrees(stagger_rad),
            "_Zweifel":            2 * (pitch / Cax) * (tb1 + tb2) * cb2**2,
        }

        results[row_name] = blade

    return results['stator'], results['rotor']



