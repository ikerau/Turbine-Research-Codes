#  EFFICIENCY
# ═══════════════════════════════════════════════════════════════════════════════
def _compute_eta(kin, states, gas, composition):
    """
    Total-to-total efficiency using kin and states dicts directly.
    """
    Pt_in = float(kin['Pt0'].to('Pa').magnitude)
    Tt_in = float(kin['Tt0'].to('K').magnitude)

    # ── Inlet total enthalpy and entropy ──────────────────────────────────
    gas.TPX = Tt_in, Pt_in, composition
    ht_in   = Q_(gas.enthalpy_mass, 'J/kg')
    s_in    = gas.entropy_mass

    # ── Isentropic exit enthalpy — same entropy, actual exit Pt_abs ───────
    gas.SP  = s_in, states['Pt3_abs']
    ht_is   = Q_(gas.enthalpy_mass, 'J/kg')

    # ── Actual exit total enthalpy — absolute frame, Cθ3=0 so C3=Cm ───────
    ht_out  = Q_(states['hs3'] + 0.5 * kin['C3']**2, 'J/kg')

    dh_act  = ht_in - ht_out
    dh_is   = ht_in - ht_is
    
    # ── Isentropic exit enthalpy — same entropy, actual exit STATIC pressure ───
    gas.SP  = s_in, states['Ps3']
    h_is_ts = Q_(gas.enthalpy_mass, 'J/kg')
    

    dh_is_ts = ht_in - h_is_ts        # larger than dh_is (more expansion)
    
    eta_ts   = float((dh_act / dh_is_ts).to('').magnitude) \
            if abs(float(dh_is_ts.to('J/kg').magnitude)) > 1.0 else 0.0

    eta_tt  = float((dh_act / dh_is).to('').magnitude) \
              if abs(float(dh_is.to('J/kg').magnitude)) > 1.0 else 0.0

    return {
        "eta_tt":   eta_tt,
        "dh_act":   float(dh_act.to('J/kg').magnitude),
        "dh_is":    float(dh_is.to('J/kg').magnitude),
        "PR":       Pt_in / states['Pt3_abs'],
        "Pt_ratio": Pt_in / states['Pt3_abs'],
        "Pt3_abs":  states['Pt3_abs'],
        "eta_ts":   eta_ts,
        "dh_is_ts": float(dh_is_ts.to('J/kg').magnitude),
        "PR_ts":    Pt_in / states['Ps3'],
    }



