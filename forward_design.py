    def _safe_deg(q):
    
        if q is None:
            return float('nan')
        if hasattr(q, 'to'):
            try:
                return float(q.to('deg').magnitude)
            except Exception:
                return float('nan')
        return float(q)


    def plot_outlet_angles(curve, zoom_pr=None):

        PRs       = np.array([pt['PR']                        for pt in curve])
        alpha_s   = np.array([_safe_deg(pt['stator_out']['alpha_out']) for pt in curve])
        alpha_r   = np.array([_safe_deg(pt['rotor_out']['alpha_out'])  for pt in curve])
        choke     = [pt['choke']                              for pt in curve]
        lam_s     = np.array([float(pt['stator_out'].get('lam_exit', float('nan'))) for pt in curve])
        lam_r     = np.array([float(pt['rotor_out' ].get('lam_exit', float('nan'))) for pt in curve])
        choked_s  = np.array([bool(pt['stator_out'].get('choked', False))          for pt in curve])
        choked_r  = np.array([bool(pt['rotor_out' ].get('choked', False))          for pt in curve])

        # Detect rotor-choke transition (first index where rotor goes choked)
        transitions = np.where(np.diff(choked_r.astype(int)) == 1)[0]
        pr_rotor_choke = PRs[transitions[0] + 1] if len(transitions) else None

        # Detect stator-choke transition
        transitions_s = np.where(np.diff(choked_s.astype(int)) == 1)[0]
        pr_stator_choke = PRs[transitions_s[0] + 1] if len(transitions_s) else None

        # Auto-zoom around rotor choke
        if zoom_pr is None and pr_rotor_choke is not None:
            zoom_pr = (pr_rotor_choke - 0.2, pr_rotor_choke + 0.2)

        fig, axes = plt.subplots(2, 2, figsize=(12, 8), sharex='col')

        # ── Top-left: full sweep α_stator ──────────────────────────────────────
        ax = axes[0, 0]
        ax.plot(PRs, alpha_s, 'o-', ms=3, lw=1, color='steelblue', label='Stator α_out')
        if pr_stator_choke is not None:
            ax.axvline(pr_stator_choke, color='steelblue', ls=':', alpha=0.5,
                    label=f'Stator choke  PR={pr_stator_choke:.3f}')
        if pr_rotor_choke is not None:
            ax.axvline(pr_rotor_choke, color='crimson', ls=':', alpha=0.5,
                    label=f'Rotor choke  PR={pr_rotor_choke:.3f}')
        ax.set_ylabel('Stator α_out [°]')
        ax.set_title('Full sweep')
        ax.grid(True, ls='--', alpha=0.3)
        ax.legend(fontsize=8, loc='best')

        # ── Bottom-left: full sweep α_rotor ────────────────────────────────────
        ax = axes[1, 0]
        ax.plot(PRs, alpha_r, 'o-', ms=3, lw=1, color='crimson', label='Rotor α_out')
        if pr_stator_choke is not None:
            ax.axvline(pr_stator_choke, color='steelblue', ls=':', alpha=0.5)
        if pr_rotor_choke is not None:
            ax.axvline(pr_rotor_choke, color='crimson', ls=':', alpha=0.5)
        ax.set_ylabel('Rotor α_out [°]')
        ax.set_xlabel('PR (t-t)')
        ax.grid(True, ls='--', alpha=0.3)

        # ── Top-right: zoomed α_stator ─────────────────────────────────────────
        ax = axes[0, 1]
        if zoom_pr is not None:
            mask = (PRs >= zoom_pr[0]) & (PRs <= zoom_pr[1])
        else:
            mask = np.ones_like(PRs, dtype=bool)

        # Color points by choke state for clarity
        colors_s = ['gray' if c == 'none' else
                    'steelblue' if c == 'stator' else
                    'purple' if c == 'both' else
                    'crimson' for c in np.array(choke)[mask]]
        ax.scatter(PRs[mask], alpha_s[mask], c=colors_s, s=25, zorder=3)
        ax.plot(PRs[mask], alpha_s[mask], '-', color='steelblue', lw=0.8, alpha=0.4, zorder=2)

        if pr_rotor_choke is not None and zoom_pr[0] <= pr_rotor_choke <= zoom_pr[1]:
            ax.axvline(pr_rotor_choke, color='crimson', ls=':', alpha=0.6,
                    label=f'Rotor choke')

        # Annotate λ for points near the transition
        for i in np.where(mask)[0]:
            if abs(PRs[i] - (pr_rotor_choke or 1e9)) < 0.06:
                ax.annotate(f'λ={lam_s[i]:.3f}',
                            xy=(PRs[i], alpha_s[i]),
                            xytext=(3, 6), textcoords='offset points',
                            fontsize=7, color='dimgray')

        ax.set_ylabel('Stator α_out [°]')
        ax.set_title(f'Zoom: PR ∈ [{zoom_pr[0]:.3f}, {zoom_pr[1]:.3f}]' if zoom_pr else 'Zoom')
        ax.grid(True, ls='--', alpha=0.3)
        ax.legend(fontsize=8, loc='best')

        # ── Bottom-right: zoomed α_rotor ──────────────────────────────────────
        ax = axes[1, 1]
        colors_r = ['gray' if c == 'none' else
                    'steelblue' if c == 'stator' else
                    'purple' if c == 'both' else
                    'crimson' for c in np.array(choke)[mask]]
